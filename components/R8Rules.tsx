"use client";

import { useEffect, useMemo, useState } from "react";
import { useLang } from "@/lib/i18n";
import { dontwarnFromErrors, GROUPS, LIBS, type Lib } from "@/data/r8Rules";

const PRESETS: { label: string; ids: string[] }[] = [
  { label: "Typical Android app", ids: ["models", "crash", "retrofit", "okhttp", "gson", "room", "hilt", "compose", "coroutines", "firebase", "crashlytics", "glide"] },
  { label: "Flutter app", ids: ["crash", "flutter-playcore", "flutter-plugins", "firebase"] },
];
const NEED_LABEL = { add: "Add rules", check: "Sometimes", builtin: "Built in" } as const;

// ProGuard / R8 rules generator: tick libraries, get a commented proguard-rules.pro.
export default function R8Rules() {
  const { t } = useLang();
  const [picked, setPicked] = useState<Set<string>>(new Set(["models", "crash"]));
  const [appPkg, setAppPkg] = useState("");
  const [modelPkg, setModelPkg] = useState("");
  const [errors, setErrors] = useState("");
  const [gradle, setGradle] = useState<"kts" | "groovy">("kts");
  const [copied, setCopied] = useState<string | null>(null);

  const toggle = (id: string) =>
    setPicked((s) => {
      const n = new Set(s);
      if (n.has(id)) n.delete(id);
      else n.add(id);
      return n;
    });

  const chosen = LIBS.filter((l) => picked.has(l.id));
  const withRules = chosen.filter((l) => l.rules && l.need !== "builtin");
  const builtIn = chosen.filter((l) => l.need === "builtin");
  const extra = useMemo(() => dontwarnFromErrors(errors), [errors]);
  const ctx = { appPkg, modelPkg: modelPkg || (appPkg ? `${appPkg.trim()}.data.model` : "") };

  const file = useMemo(() => {
    const lines = ["# proguard-rules.pro", "# Generated by Hang Daro's ProGuard / R8 Rules Generator.", "# Libraries not listed here ship their own rules.", ""];
    const seen = new Set<string>();
    for (const l of withRules) {
      const rules = l.rules!(ctx).filter((r) => {
        // Avoid repeating identical single-line rules (e.g. keepattributes shared by two libraries).
        if (!r.startsWith("-") || r.endsWith("{")) return true;
        if (seen.has(r)) return false;
        seen.add(r);
        return true;
      });
      if (!rules.length) continue;
      lines.push(`# ---- ${l.name} ----`);
      if (l.need === "check") lines.push("# Only needed in some setups: see the note in the generator.");
      lines.push(...rules, "");
    }
    if (extra.length) lines.push("# ---- From your R8 \"Missing class\" errors ----", ...extra, "");
    return lines.join("\n");
  }, [withRules, extra, ctx.appPkg, ctx.modelPkg]); // eslint-disable-line react-hooks/exhaustive-deps

  const gradleText =
    gradle === "kts"
      ? `android {\n    buildTypes {\n        release {\n            isMinifyEnabled = true\n            isShrinkResources = true\n            proguardFiles(\n                getDefaultProguardFile("proguard-android-optimize.txt"),\n                "proguard-rules.pro"\n            )\n        }\n    }\n}`
      : `android {\n    buildTypes {\n        release {\n            minifyEnabled true\n            shrinkResources true\n            proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'\n        }\n    }\n}`;

  const copy = (key: string, text: string) =>
    navigator.clipboard.writeText(text).then(() => {
      setCopied(key);
      setTimeout(() => setCopied(null), 1400);
    });

  const [dl, setDl] = useState("");
  useEffect(() => {
    const u = URL.createObjectURL(new Blob([file], { type: "text/plain" }));
    setDl(u);
    return () => URL.revokeObjectURL(u);
  }, [file]);

  return (
    <div className="r8">
      <section className="r8-pick">
        <div className="r8-pkgs">
          <label className="field">
            <span>{t("App package (optional)")}</span>
            <input value={appPkg} onChange={(e) => setAppPkg(e.target.value.trim())} placeholder="com.darohang.app" spellCheck={false} autoCapitalize="off" />
          </label>
          <label className="field">
            <span>{t("Package of your JSON models")}</span>
            <input value={modelPkg} onChange={(e) => setModelPkg(e.target.value.trim())} placeholder={ctx.modelPkg || "com.darohang.app.data.model"} spellCheck={false} autoCapitalize="off" />
          </label>
        </div>

        <div className="r8-presets">
          <span>{t("Quick start:")}</span>
          {PRESETS.map((p) => (
            <button key={p.label} className="mini-tool" type="button" onClick={() => setPicked(new Set(p.ids))}>
              {t(p.label)}
            </button>
          ))}
          <button className="mini-tool" type="button" onClick={() => setPicked(new Set())}>
            {t("Clear all")}
          </button>
        </div>

        {GROUPS.map((g) => (
          <fieldset key={g} className="r8-group">
            <legend>{t(g)}</legend>
            {LIBS.filter((l) => l.group === g).map((l) => (
              <LibRow key={l.id} lib={l} on={picked.has(l.id)} onToggle={() => toggle(l.id)} />
            ))}
          </fieldset>
        ))}

        <fieldset className="r8-group">
          <legend>{t("Fix \"Missing class\" build errors")}</legend>
          <p className="r8-hint">{t("Paste the R8 error from your release build (or the contents of build/outputs/mapping/release/missing_rules.txt). The matching -dontwarn lines are added to the file.")}</p>
          <textarea className="fp-paste" rows={5} value={errors} onChange={(e) => setErrors(e.target.value)} placeholder={"ERROR: Missing class com.google.android.play.core.splitcompat.SplitCompatApplication (referenced from: …)"} spellCheck={false} />
          {errors.trim() && <small className="r8-hint">{t(extra.length === 1 ? "{n} line added" : "{n} lines added", { n: extra.length })}</small>}
        </fieldset>
      </section>

      <section className="r8-out">
        <div className="r8-file">
          <header className="pj-head">
            <b>proguard-rules.pro</b>
            <span className="eh-head-actions">
              <button className="mini-tool" type="button" onClick={() => copy("file", file)}>
                {copied === "file" ? t("✓ Copied") : t("Copy")}
              </button>
              <a className="mini-tool" href={dl} download="proguard-rules.pro">
                ⬇ {t("Download")}
              </a>
            </span>
          </header>
          <pre>{withRules.length || extra.length ? file : t("Tick a library on the left to add its rules.")}</pre>
        </div>

        {builtIn.length > 0 && (
          <div className="r8-builtin">
            <b>✓ {t("No rules needed for these")}</b>
            <p>{t("They ship their own rules, which R8 applies automatically:")}</p>
            <p className="r8-chips">
              {builtIn.map((l) => (
                <i key={l.id}>{l.name}</i>
              ))}
            </p>
          </div>
        )}

        <div className="r8-file">
          <header className="pj-head">
            <b>{t("Turn on R8 in app/build.gradle")}</b>
            <span className="eh-head-actions">
              <span className="pj-views">
                {(["kts", "groovy"] as const).map((g) => (
                  <button key={g} type="button" className={gradle === g ? "on" : undefined} onClick={() => setGradle(g)}>
                    {g === "kts" ? ".kts" : "Groovy"}
                  </button>
                ))}
              </span>
              <button className="mini-tool" type="button" onClick={() => copy("gradle", gradleText)}>
                {copied === "gradle" ? t("✓ Copied") : t("Copy")}
              </button>
            </span>
          </header>
          <pre>{gradleText}</pre>
        </div>

        <details className="r8-tips">
          <summary>{t("Testing tips")}</summary>
          <ul>
            <li>{t("Always test a release build on a real phone before uploading: install it with flutter build apk --release or ./gradlew assembleRelease.")}</li>
            <li>{t("If something breaks only in release, check the R8 output in build/outputs/mapping/release/: usage.txt lists removed code, mapping.txt maps renamed names.")}</li>
            <li>{t("Keep mapping.txt for every release (Play Console stores it for AABs) so crash reports can be decoded.")}</li>
          </ul>
        </details>
      </section>
    </div>
  );
}

function LibRow({ lib, on, onToggle }: { lib: Lib; on: boolean; onToggle: () => void }) {
  const { t } = useLang();
  return (
    <label className={`r8-lib${on ? " on" : ""}`}>
      <input type="checkbox" checked={on} onChange={onToggle} />
      <span className="r8-lib-main">
        <span className="r8-lib-name">
          {t(lib.name)} <em className={`r8-need n-${lib.need}`}>{t(NEED_LABEL[lib.need])}</em>
        </span>
        {on && <small>{t(lib.note)}</small>}
      </span>
    </label>
  );
}
